import dataclasses
import re
from pathlib import Path

import ipxact
import xactflow

# A simple SystemVerilog identifier (IEEE 1800 5.6): the form every name rtlgen writes must
# have. Keywords are not checked yet (D5).
_IDENTIFIER = re.compile(r"[A-Za-z_][A-Za-z0-9_$]*")

# What in an expression looks like a name but is not a parameter: strings, based literals
# (8'hA5, 'hFF, '1), numbers (1e5) and $functions. A value with any other name in it refers
# to a parameter (D7).
_NOT_A_PARAMETER = re.compile(
	r'"(?:[^"\\]|\\.)*"'
	r"|(?:\d[\d_]*\s*)?'[sS]?[bBoOdDhH]\s*[0-9a-fA-FxXzZ?_]+"
	r"|'[01xXzZ]"
	r"|\d[\d_]*(?:\.\d[\d_]*)?(?:[eE][+-]?\d[\d_]*)?"
	r"|\$[A-Za-z_][A-Za-z0-9_$]*"
)

# The start of the first line of every file rtlgen writes, and the only kind of file it
# overwrites (D2).
_MARKER = "// Generated by rtlgen"


class RtlExporter(xactflow.Exporter):
	name = "rtl"

	def export(self, library, output_dir, **options):
		if options:
			raise ValueError(f"unknown options: {', '.join(options)}")

		designs = list(library.targets(ipxact.Design))
		if not designs:
			raise TypeError("needs a design to export, such as a design XML file")
		if len(designs) > 1:
			raise ValueError(f"can export one design at a time, got {len(designs)}")
		design = designs[0]

		if next(library.targets(ipxact.DesignConfiguration), None) is not None:
			raise ValueError("design configurations are not supported yet")

		linked = xactflow.link(design, library)
		errors = [d for d in linked.diagnostics if d.severity is xactflow.Severity.ERROR]
		if errors:
			raise ValueError("the design does not link: " + "; ".join(d.message for d in errors))

		module_name = _module_name(linked)
		port_lines = _top_port_lines(linked)
		instances = _instance_lines(linked)
		nets, _ = _ad_hoc_nets(linked)
		net_lines = "".join(
			f"  wire [{width - 1}:0] {net};\n" if width > 1 else f"  wire {net};\n"
			for net, width in nets
		)
		if net_lines:
			net_lines += "\n"
		if port_lines:
			header = f"module {module_name} (\n" + ",\n".join(port_lines) + "\n);\n"
		else:
			header = f"module {module_name};\n"

		output_dir = Path(output_dir)
		output_dir.mkdir(parents=True, exist_ok=True)
		text = f"{_MARKER} from {linked.vlnv}. Do not edit.\n{header}{net_lines}{instances}endmodule\n"
		_write(output_dir / f"{module_name}.sv", text)


def _write(path, text):
	"""Write a generated file, refusing to overwrite a file rtlgen did not write (D2)."""
	if path.exists():
		with path.open(errors="replace") as existing:
			first_line = existing.readline()
		if not first_line.startswith(_MARKER):
			raise ValueError(
				f"{path} exists and was not written by rtlgen (its first line is not "
				f"'{_MARKER} ...'): not overwriting it"
			)
	path.write_text(text)


def _check_name(name, what):
	"""Refuse a name rtlgen would write unless it is a simple SystemVerilog identifier (D5)."""
	if not _IDENTIFIER.fullmatch(name):
		raise ValueError(
			f"{what} is not a legal SystemVerilog identifier: a letter or _, then letters, "
			"digits, _ or $"
		)


def _instance_lines(linked):
	"""Each instance, in design order: '  <module> <instance> ();', with its module parameters
	one per line in '#( ... )' and its connected ports one per line in '( ... )', in the
	component's port order, when it has any (steps 2 to 4)."""
	_, ports = _ad_hoc_nets(linked)
	lines = ""
	for instance in linked.instances.values():
		_check_name(
			instance.instance_name,
			f"instance name '{instance.instance_name}' in design {linked.vlnv}",
		)
		instantiation = _instance_instantiation(instance)
		parameters = _module_parameter_lines(instance, instantiation)
		connected = ports.get(instance.instance_name, {})
		port_lines = [
			f"    .{port.name}({connected[port.name]})"
			for port in instance.component.model.ports
			if port.name in connected
		]
		lines += f"  {instantiation.module_name}"
		if parameters:
			lines += " #(\n" + ",\n".join(parameters) + "\n  )"
		lines += f" {instance.instance_name}"
		if port_lines:
			lines += " (\n" + ",\n".join(port_lines) + "\n  );\n"
		else:
			lines += " ();\n"
	return lines


def _ad_hoc_keys(linked, name):
	"""The ports an ad hoc connection touches, as keys: (instance name, port name) for an
	instance's port, (None, port name) for a top port."""
	keys = []
	for reference in linked.ad_hoc_connections[name]:
		keys.append((reference.instance.instance_name, reference.port.name))
	for external in linked.ad_hoc_external_ports.get(name, []):
		keys.append((None, external.port.name))
	return keys


def _ad_hoc_groups(linked):
	"""The ad hoc connections grouped into nets, where connections that share a port, an
	instance's or a top port (_ad_hoc_keys), directly or through other connections, are one net.
	Each group lists connection names in design order from its first one."""
	by_port = {}
	for name in linked.ad_hoc_connections:
		for key in _ad_hoc_keys(linked, name):
			by_port.setdefault(key, []).append(name)
	groups = []
	seen = set()
	for name in linked.ad_hoc_connections:
		if name in seen:
			continue
		group = [name]
		seen.add(name)
		for member in group:
			for key in _ad_hoc_keys(linked, member):
				for other in by_port[key]:
					if other not in seen:
						seen.add(other)
						group.append(other)
		groups.append(group)
	return groups


def _ad_hoc_nets(linked):
	"""The ad hoc nets (steps 4 and 5): the (net name, width) of each net to declare as a wire,
	in design order, and instance name -> {port name -> net name}. Connections that share a
	port are one net (_ad_hoc_groups); a port listed twice is written once. A net that reaches
	a top port is that port: it takes the port's name and is not declared, as the module header
	declares it. A net that reaches two top ports is refused. Any other net is named after its
	first connection in design order. The instance ports on a net must have the same width and
	bit order. Any mix of directions is accepted (the nets are wires). What rtlgen can't write
	yet is refused: a tiedValue here, and ports in _check_reference."""
	nets = []
	ports = {}
	sources = {}
	for ad_hoc in linked.design.ad_hoc_connections:
		if ad_hoc.name in sources:
			raise ValueError(
				f"design {linked.vlnv} has two ad hoc connections named '{ad_hoc.name}': "
				"names must be unique"
			)
		sources[ad_hoc.name] = ad_hoc
	model = linked.component.model or ipxact.Model()
	top_resolve = xactflow.parameter_resolver(linked.component.parameters)
	top_names = {
		port.name for port in model.ports
		if port.wire is None or port.wire.direction is not ipxact.Direction.PHANTOM
	}
	reached = set()
	for group in _ad_hoc_groups(linked):
		top_ports = []
		for member in group:
			for external in linked.ad_hoc_external_ports.get(member, []):
				if external.port.name not in top_ports:
					top_ports.append(external.port.name)
		reached.update(top_ports)
		if len(top_ports) > 1:
			raise ValueError(
				"the net of ad hoc connection(s) " + ", ".join(f"'{m}'" for m in group)
				+ " joins top ports " + ", ".join(f"'{p}'" for p in top_ports)
				+ ": a net between top ports is not supported yet"
			)
		if top_ports:
			name = top_ports[0]
		else:
			name = group[0]
			_check_name(name, f"ad hoc connection name '{name}' in design {linked.vlnv}")
			if name in top_names:
				raise ValueError(
					f"ad hoc connection '{name}' has the same name as a top port: "
					"its net and the port would clash in the module"
				)
			if name in linked.instances:
				raise ValueError(
					f"ad hoc connection '{name}' has the same name as an instance: its net and the "
					"instance would clash in the module"
				)
		references = []
		for member in group:
			if sources[member].tied_value is not None:
				raise ValueError(
					f"ad hoc connection '{member}' has a tiedValue: "
					"tie-offs are not supported yet"
				)
			for reference in linked.ad_hoc_connections[member]:
				_check_reference(member, reference)
			for external in linked.ad_hoc_external_ports.get(member, []):
				_check_external(member, external)
			references.extend(linked.ad_hoc_connections[member])
		shapes = []
		for reference in references:
			bounds = _port_range(
				reference.port,
				_resolver(reference.instance),
				f"instance '{reference.instance.instance_name}'",
			)
			if bounds is None:
				width = 1
			else:
				left, right = bounds
				width = abs(left - right) + 1
			shapes.append((f"{reference.instance.instance_name}.{reference.port.name}", bounds, width))
		if top_ports:
			top_port = next(
				external.port
				for member in group
				for external in linked.ad_hoc_external_ports.get(member, [])
			)
			bounds = _port_range(top_port, top_resolve, f"component {linked.component.vlnv}")
			if bounds is None:
				width = 1
			else:
				left, right = bounds
				width = abs(left - right) + 1
			shapes.append((f"top port {top_port.name}", bounds, width))
		if len(group) == 1:
			label = f"ad hoc connection '{group[0]}'"
		else:
			label = (
				"ad hoc connections " + ", ".join(f"'{m}'" for m in group)
				+ " (one net: they share a port)"
			)
		listed = ", ".join(
			f"{where} " + (f"[{bounds[0]}:{bounds[1]}]" if bounds else "1 bit")
			for where, bounds, width in shapes
		)
		if len({width for where, bounds, width in shapes}) > 1:
			raise ValueError(
				f"{label} joins ports of different widths ({listed}): "
				"part selects are not supported yet"
			)
		if len({bounds[0] > bounds[1] for where, bounds, width in shapes if width > 1}) > 1:
			raise ValueError(
				f"{label} joins ports with opposite bit orders ({listed}): "
				"not supported yet"
			)
		if top_ports:
			# Decision 8: a top input is driven from outside, so no instance output may drive
			# it; a top output needs an instance output or inout to drive it. A top inout
			# takes any mix.
			drivers = [
				f"{reference.instance.instance_name}.{reference.port.name}"
				for reference in references
				if reference.port.wire.direction is ipxact.Direction.OUT
			]
			inouts = [
				reference for reference in references
				if reference.port.wire.direction is ipxact.Direction.INOUT
			]
			if top_port.wire.direction is ipxact.Direction.IN and drivers:
				raise ValueError(
					f"{label} drives top input '{top_port.name}' from instance output(s) "
					f"{', '.join(drivers)}: the input is driven from outside the module"
				)
			if top_port.wire.direction is ipxact.Direction.OUT and not (drivers or inouts):
				raise ValueError(
					f"{label} reaches top output '{top_port.name}', but no output or inout "
					"drives it: tie-offs are not supported yet"
				)
		if not top_ports:
			nets.append((name, width))
		for reference in references:
			ports.setdefault(reference.instance.instance_name, {})[reference.port.name] = name
	for port in model.ports:
		if port.wire and port.wire.direction is ipxact.Direction.OUT and port.name not in reached:
			raise ValueError(
				f"top output '{port.name}' of component {linked.component.vlnv} is not reached "
				"by any connection, so nothing drives it: tie-offs are not supported yet"
			)
	return nets, ports


def _check_reference(connection, reference):
	"""Refuse a port reference that rtlgen can't write yet."""
	_check_name(
		reference.port.name,
		f"port name '{reference.port.name}' of instance '{reference.instance.instance_name}'"
	)
	if reference.port.wire is None:
		raise ValueError(
			f"ad hoc connection '{connection}' connects port '{reference.port.name}' "
			f"of instance '{reference.instance.instance_name}', which is "
			"not a wire port: transactional and structured ports are not supported yet"
		)
	if reference.port.wire.direction is ipxact.Direction.PHANTOM:
		raise ValueError(
			f"ad hoc connection '{connection}' connects port '{reference.port.name}' "
			f"of instance '{reference.instance.instance_name}', which is "
			"phantom: it is not in the module"
		)
	if reference.port.arrays:
		raise ValueError(
			f"ad hoc connection '{connection}' connects port '{reference.port.name}' "
			f"of instance '{reference.instance.instance_name}', which is "
			"an array: port arrays are not supported yet"
		)
	if reference.source.part_select is not None:
		raise ValueError(
			f"ad hoc connection '{connection}' takes a part of port '{reference.port.name}' "
			f"of instance '{reference.instance.instance_name}' (partSelect): "
			"part selects are not supported yet"
		)
	if reference.source.sub_port_refs:
		raise ValueError(
			f"ad hoc connection '{connection}' connects a sub-port of port '{reference.port.name}' "
			f"of instance '{reference.instance.instance_name}' (subPortReference): "
			"sub-ports of structured ports are not supported yet"
		)


def _check_external(connection, external):
	"""Refuse a top-port reference that rtlgen can't write yet (decisions 10 and 11)."""
	where = f"ad hoc connection '{connection}' connects top port '{external.port.name}'"
	if external.port.wire is None:
		raise ValueError(
			f"{where}, which is not a wire port: transactional and structured ports are "
			"not supported yet"
		)
	if external.port.wire.direction is ipxact.Direction.PHANTOM:
		raise ValueError(f"{where}, which is phantom: it is not in the module")
	if external.source.part_select is not None:
		raise ValueError(
			f"{where} through a partSelect: part selects are not supported yet"
		)
	if external.source.sub_port_refs:
		raise ValueError(
			f"{where} through a subPortReference: sub-ports of structured ports are not "
			"supported yet"
		)


def _port_range(port, resolve, owner):
	"""A port's (left, right) bounds, worked out with resolve, or None for a port with no
	vector (one bit). A port with several vectors is refused for now, naming the port and
	its owner (an instance, or the containing component for a top port)."""
	vectors = port.wire.vectors
	if not vectors:
		return None
	if len(vectors) > 1:
		raise ValueError(
			f"port '{port.name}' of {owner} has {len(vectors)} "
			"vectors: multi-dimensional ports are not supported yet"
		)
	try:
		left = xactflow.evaluate(vectors[0].left, resolve)
		right = xactflow.evaluate(vectors[0].right, resolve)
	except xactflow.ExpressionError as error:
		raise ValueError(
			f"{owner}: the range of port '{port.name}' cannot be "
			f"worked out: {error}"
		) from error
	return (left, right)


def _resolver(instance):
	"""The resolver for an instance's values: its component's parameters, with the design's
	overrides in place (D6 item 2)."""
	overrides = instance.source.component_ref.config_element_values
	parameter_ids = {p.parameter_id for p in instance.component.parameters}
	for reference_id in overrides:
		if reference_id not in parameter_ids:
			raise ValueError(
				f"instance '{instance.instance_name}' overrides '{reference_id}', which is not "
				f"a parameter of component {instance.component.vlnv}"
			)
	# The component's parameters, each with the design's override for this instance in place
	# of its value. The override replaces only the text: the limits stay the parameter's.
	parameters = [
		dataclasses.replace(
			parameter,
			value=dataclasses.replace(parameter.value, value=overrides[parameter.parameter_id].value),
		)
		if parameter.parameter_id in overrides
		else parameter
		for parameter in instance.component.parameters
	]
	return xactflow.parameter_resolver(parameters)


def _module_parameter_lines(instance, instantiation):
	"""'    .<name>(<value>)' for every module parameter of the instantiation, in its order, with
	its value in this design (D6, D7)."""
	names = set()
	resolve = _resolver(instance)
	for parameter in instantiation.module_parameters:
		_check_name(
			parameter.name,
			f"module parameter name '{parameter.name}' of instance '{instance.instance_name}'"
		)
		if parameter.name in names:
			raise ValueError(
				f"instance '{instance.instance_name}' gives module parameter '{parameter.name}' twice"
			)
		names.add(parameter.name)
	return [
		f"    .{parameter.name}({_module_parameter_value(parameter, resolve, instance)})"
		for parameter in instantiation.module_parameters
	]


def _module_parameter_value(parameter, resolve, instance):
	"""A module parameter's value as written: as it stands when it refers to no parameter,
	else worked out by XactFlow's evaluator and written as plain decimal (D7)."""
	if parameter.usage_type not in ("typed", None):
		raise ValueError(
			f"instance '{instance.instance_name}': module parameter '{parameter.name}' has "
			f"usageType '{parameter.usage_type}': only typed module parameters are supported"
		)
	text = parameter.value.value.strip()
	if not _IDENTIFIER.search(_NOT_A_PARAMETER.sub(" ", text)):
		return text
	try:
		return str(xactflow.evaluate(parameter, resolve))
	except xactflow.ExpressionError as error:
		raise ValueError(
			f"instance '{instance.instance_name}': module parameter '{parameter.name}' "
			f"('{text}') cannot be worked out: {error}"
		) from error


def _module_name(linked):
	"""The name of the module generated for a linked design, as D1 decides it. Refuses the
	top's own parameters (D8)."""
	if linked.design.parameters:
		raise ValueError(
			f"design {linked.vlnv} has parameters of its own: the top's parameters are not "
			"supported yet"
		)
	component = linked.component
	if component is None:  # D1 item 2
		raise ValueError(
			f"no component in the library holds design {linked.vlnv}: add the component that "
			"holds it (with archidesc, the --then component output)"
		)
	model = component.model or ipxact.Model()
	design_instantiations = {i.name: i for i in model.design_instantiations}
	component_instantiations = {i.name: i for i in model.component_instantiations}

	# View name -> module name, for each view whose designInstantiationRef leads to the
	# design (D1 item 1), each of which must give a name (D1 item 3).
	names = {}
	for view in model.views:
		design_instantiation = design_instantiations.get(view.design_instantiation_ref)
		if design_instantiation is None or design_instantiation.design_ref.vlnv != linked.vlnv:
			continue
		where = f"view '{view.name}' of component {component.vlnv}"
		if view.component_instantiation_ref is None:
			raise ValueError(f"{where} has no componentInstantiationRef, so it names no module")
		instantiation = _component_instantiation(view, component_instantiations, where)
		if instantiation.module_parameters:
			raise ValueError(
				f"{where} gives the top module parameters: the top's parameters are not "
				"supported yet"
			)
		names[view.name] = instantiation.module_name

	if not names:  # D1 item 6
		raise ValueError(
			f"no view of component {component.vlnv} instantiates design {linked.vlnv} through a "
			"designInstantiationRef (a view through a design configuration is not supported yet)"
		)
	if len(set(names.values())) > 1:  # D1 item 4
		listed = ", ".join(f"view '{view}' gives '{name}'" for view, name in names.items())
		raise ValueError(
			f"the views of component {component.vlnv} instantiating design {linked.vlnv} give "
			f"different module names: {listed}"
		)
	module_name = next(iter(names.values()))
	_check_name(module_name, f"module name '{module_name}' from component {component.vlnv}")
	return module_name


def _top_port_lines(linked):
	"""The module header's port lines, '  <direction> wire [<left>:<right>] <name>' (no range for
	one bit): one for each port of the containing component, connected or not, in its order,
	with its bounds worked out with the component's parameters and kept as they are (D14). A
	phantom port is not in the module, so it is left out. A port rtlgen can't declare yet is
	refused: one that is not a wire port, an array, one with several vectors (in _port_range),
	or one whose name is not a legal identifier or is an instance's (D16, D17)."""
	component = linked.component
	model = component.model or ipxact.Model()
	resolve = xactflow.parameter_resolver(component.parameters)
	lines = []
	dir_kws = {
		ipxact.Direction.IN: "input",
		ipxact.Direction.OUT: "output",
		ipxact.Direction.INOUT: "inout",
	}
	for port in model.ports:
		if port.wire is None:
			raise ValueError(
				f"top port '{port.name}' of component {component.vlnv} is not a wire port: "
				"transactional and structured ports are not supported yet"
			)
		if port.wire.direction is ipxact.Direction.PHANTOM:
			continue
		_check_name(port.name, f"top port name '{port.name}' of component {component.vlnv}")
		if port.name in linked.instances:
			raise ValueError(
				f"top port '{port.name}' of component {component.vlnv} has the same name as "
				"an instance: the port and the instance would clash in the module"
			)
		if port.arrays:
			raise ValueError(
				f"top port '{port.name}' of component {component.vlnv} is an array: "
				"port arrays are not supported yet"
			)
		bounds = _port_range(port, resolve, f"component {component.vlnv}")
		if bounds is None:
			range_text = ""
		else:
			left, right = bounds
			range_text = f" [{left}:{right}]"
		lines.append(f"  {dir_kws[port.wire.direction]} wire{range_text} {port.name}")
	return lines


def _instance_instantiation(instance):
	"""The component instantiation an instance instantiates: the one its component's views
	with a componentInstantiationRef lead to, whose moduleName names the module (D4)."""
	component = instance.component
	model = component.model or ipxact.Model()
	component_instantiations = {i.name: i for i in model.component_instantiations}
	who = f"component {component.vlnv} (instance '{instance.instance_name}')"

	# A view that instantiates a design makes the component hierarchical, which waits for
	# step 8, whichever view would give the module name.
	for view in model.views:
		if view.design_instantiation_ref or view.design_configuration_instantiation_ref:
			raise ValueError(
				f"view '{view.name}' of {who} instantiates a design, so the component is "
				"hierarchical: hierarchical components are not supported yet"
			)

	# View name -> component instantiation, for each view with a componentInstantiationRef. A
	# view with none (documentation, say) is skipped.
	chosen = {}
	for view in model.views:
		if view.component_instantiation_ref is None:
			continue
		where = f"view '{view.name}' of {who}"
		component_instantiation = _component_instantiation(view, component_instantiations, where)
		# Only SystemVerilog, compared ignoring case. A missing language is accepted.
		language = (component_instantiation.language or "").strip()
		if language and language.lower() != "systemverilog":
			raise ValueError(
				f"component instantiation '{component_instantiation.name}' of {where} is in "
				f"language '{language}': only SystemVerilog is supported"
			)
		# IEEE 1685-2022: a virtual component "shall not be netlisted". Refused for now.
		if component_instantiation.is_virtual:
			raise ValueError(
				f"component instantiation '{component_instantiation.name}' of {where} is virtual "
				"(isVirtual): virtual components are not supported yet"
			)
		chosen[view.name] = component_instantiation

	if not chosen:
		raise ValueError(
			f"no view of {who} has a componentInstantiationRef, so nothing names its module"
		)
	if len({i.module_name for i in chosen.values()}) > 1:
		listed = ", ".join(f"view '{view}' gives '{i.module_name}'" for view, i in chosen.items())
		raise ValueError(f"the views of {who} give different module names: {listed}")
	parameter_lines = {view: _module_parameter_lines(instance, i) for view, i in chosen.items()}
	if len({tuple(lines) for lines in parameter_lines.values()}) > 1:
		listed = "; ".join(
			f"view '{view}' gives {', '.join(line.strip() for line in lines) or 'none'}"
			for view, lines in parameter_lines.items()
		)
		raise ValueError(f"the views of {who} give different module parameters: {listed}")
	instantiation = next(iter(chosen.values()))
	_check_name(instantiation.module_name, f"module name '{instantiation.module_name}' of {who}")
	return instantiation


def _component_instantiation(view, component_instantiations, where):
	"""The component instantiation a view's componentInstantiationRef names, refusing one that
	does not exist or gives no moduleName (D1 item 3, and D4 for instances)."""
	component_instantiation = component_instantiations.get(view.component_instantiation_ref)
	if component_instantiation is None:
		raise ValueError(
			f"{where} refers to component instantiation "
			f"'{view.component_instantiation_ref}', which the component does not have"
		)
	if not component_instantiation.module_name:
		raise ValueError(
			f"component instantiation '{component_instantiation.name}' of {where} "
			"has no moduleName"
		)
	return component_instantiation
