import dataclasses
import re
from pathlib import Path

import ipxact
import xactflow

# A simple SystemVerilog identifier (IEEE 1800 5.6): the form every name rtlgen writes must
# have. Keywords are not checked yet (D5).
_IDENTIFIER = re.compile(r"[A-Za-z_][A-Za-z0-9_$]*")

# What in an expression looks like a name but is not a parameter: strings, based literals
# (8'hA5, 'hFF, '1), numbers (1e5) and $functions. A value with any other name in it refers
# to a parameter (D7).
_NOT_A_PARAMETER = re.compile(
	r'"(?:[^"\\]|\\.)*"'
	r"|(?:\d[\d_]*\s*)?'[sS]?[bBoOdDhH]\s*[0-9a-fA-FxXzZ?_]+"
	r"|'[01xXzZ]"
	r"|\d[\d_]*(?:\.\d[\d_]*)?(?:[eE][+-]?\d[\d_]*)?"
	r"|\$[A-Za-z_][A-Za-z0-9_$]*"
)

# A SystemVerilog fill literal ('0, '1, 'x, 'z), which a tie value can't have (step 7c
# decision 7): xactflow works '1 out as 1, not as all ones.
_FILL = re.compile(r"'[01xXzZ]")

# The start of the first line of every file rtlgen writes, and the only kind of file it
# overwrites (D2).
_MARKER = "// Generated by rtlgen"


class RtlExporter(xactflow.Exporter):
	name = "rtl"

	def export(self, library, output_dir, **options):
		if options:
			raise ValueError(f"unknown options: {', '.join(options)}")

		designs = list(library.targets(ipxact.Design))
		if not designs:
			raise TypeError("needs a design to export, such as a design XML file")
		if len(designs) > 1:
			raise ValueError(f"can export one design at a time, got {len(designs)}")
		design = designs[0]

		if next(library.targets(ipxact.DesignConfiguration), None) is not None:
			raise ValueError("design configurations are not supported yet")

		linked = xactflow.link(design, library)
		errors = [d for d in linked.diagnostics if d.severity is xactflow.Severity.ERROR]
		if errors:
			raise ValueError("the design does not link: " + "; ".join(d.message for d in errors))

		module_name = _module_name(linked)
		port_lines = _top_port_lines(linked)
		instances = _instance_lines(linked)
		nets, _ = _ad_hoc_nets(linked)
		groups, _ = _bus_nets(linked)
		net_lines = "".join(_wire_line(net, width) for net, width in nets)
		for name, bus in groups:
			net_lines += f"\n  // {name}\n" + "".join(_wire_line(net, width) for net, width in bus)
		if net_lines:
			net_lines += "\n"
		assign_lines = _assign_lines(linked)
		if port_lines:
			header = f"module {module_name} (\n" + ",\n".join(port_lines) + "\n);\n"
		else:
			header = f"module {module_name};\n"

		output_dir = Path(output_dir)
		output_dir.mkdir(parents=True, exist_ok=True)
		text = (
			f"{_MARKER} from {linked.vlnv}. Do not edit.\n"
			f"{header}{net_lines}{assign_lines}{instances}endmodule\n"
		)
		_write(output_dir / f"{module_name}.sv", text)


def _wire_line(net, width):
	"""'  wire [W-1:0] <net>;', or with no range for one bit (D12)."""
	return f"  wire [{width - 1}:0] {net};\n" if width > 1 else f"  wire {net};\n"


def _write(path, text):
	"""Write a generated file, refusing to overwrite a file rtlgen did not write (D2)."""
	if path.exists():
		with path.open(errors="replace") as existing:
			first_line = existing.readline()
		if not first_line.startswith(_MARKER):
			raise ValueError(
				f"{path} exists and was not written by rtlgen (its first line is not "
				f"'{_MARKER} ...'): not overwriting it"
			)
	path.write_text(text)


def _check_name(name, what):
	"""Refuse a name rtlgen would write unless it is a simple SystemVerilog identifier (D5)."""
	if not _IDENTIFIER.fullmatch(name):
		raise ValueError(
			f"{what} is not a legal SystemVerilog identifier: a letter or _, then letters, "
			"digits, _ or $"
		)


def _instance_lines(linked):
	"""Each instance, in design order: '  <module> <instance> ();', with its module parameters
	one per line in '#( ... )' and its ports one per line in '( ... )', in the component's port
	order, when it has any (steps 2 to 4): a connected port with its net, a tied one with its
	constant, or as '.<port>()' when tied 'open' (step 7c, _ties), an open one as '.<port>()'
	(step 7a, _open_port)."""
	_, ports = _ad_hoc_nets(linked)
	_, bus_ports = _bus_nets(linked)
	ties, _ = _ties(linked)
	lines = ""
	for instance in linked.instances.values():
		_check_name(
			instance.instance_name,
			f"instance name '{instance.instance_name}' in design {linked.vlnv}",
		)
		_check_required_interfaces(linked, instance)
		instantiation = _instance_instantiation(instance)
		parameters = _module_parameter_lines(instance, instantiation)
		connected = {
			**ports.get(instance.instance_name, {}),
			**bus_ports.get(instance.instance_name, {}),
			**ties.get(instance.instance_name, {}),
		}
		port_lines = []
		for port in instance.component.model.ports:
			if port.name in connected:
				port_lines.append(f"    .{port.name}({connected[port.name]})")
			elif _open_port(instance, port):
				port_lines.append(f"    .{port.name}()")
		lines += f"  {instantiation.module_name}"
		if parameters:
			lines += " #(\n" + ",\n".join(parameters) + "\n  )"
		lines += f" {instance.instance_name}"
		if port_lines:
			lines += " (\n" + ",\n".join(port_lines) + "\n  );\n"
		else:
			lines += " ();\n"
	return lines


def _open_port(instance, port):
	"""Whether an open port of an instance, one that no connection reaches, is written as
	'.<port>()' (step 7a). An output or an inout is. A phantom port is left out, as it is not in
	the module. An input is refused, as it would float, and so are a port that is not a wire
	port and an array port, which rtlgen can't write yet."""
	where = f"port '{port.name}' of instance '{instance.instance_name}'"
	if port.wire is None:
		raise ValueError(
			f"{where} is not a wire port: transactional and structured ports are not supported yet"
		)
	if port.wire.direction is ipxact.Direction.PHANTOM:
		return False
	if port.arrays:
		raise ValueError(f"{where} is an array: port arrays are not supported yet")
	_check_name(port.name, f"port name '{port.name}' of instance '{instance.instance_name}'")
	if port.wire.direction is ipxact.Direction.IN:
		raise ValueError(
			f"{where} is an input that no connection reaches, so it would float: connect it, "
			"or tie it with an ad hoc connection's tiedValue (a value, 'default' or 'open')"
		)
	return True


def _check_required_interfaces(linked, instance):
	"""Refuse a bus interface of an instance with connectionRequired that no interconnection
	uses (step 7a): IEEE 1685-2022 6.7.1.2 says the integration is then not valid, and xactflow
	does not check it (SCR 2.15)."""
	used = {
		end.bus_interface.name
		for interconnection in linked.interconnections
		for end in interconnection.endpoints
		if end.instance.instance_name == instance.instance_name
	}
	for bus_interface in instance.component.bus_interfaces:
		if bus_interface.connection_required and bus_interface.name not in used:
			raise ValueError(
				f"bus interface '{bus_interface.name}' of instance '{instance.instance_name}' "
				"requires a connection (connectionRequired), but no interconnection uses it: "
				"IEEE 1685-2022 6.7.1.2 makes the design not valid"
			)


def _ad_hoc_names(linked):
	"""The names of the design's ad hoc connections, in design order. linked.ad_hoc_connections
	leaves out a connection that reaches no instance port, such as one that ties a top output."""
	return [connection.name for connection in linked.design.ad_hoc_connections]


def _ad_hoc_references(linked, name):
	"""The instance-port references of an ad hoc connection: none for one that reaches only top
	ports."""
	return linked.ad_hoc_connections.get(name, [])


def _ad_hoc_keys(linked, name):
	"""The ports an ad hoc connection touches, as keys: (instance name, port name) for an
	instance's port, (None, port name) for a top port."""
	keys = []
	for reference in _ad_hoc_references(linked, name):
		keys.append((reference.instance.instance_name, reference.port.name))
	for external in linked.ad_hoc_external_ports.get(name, []):
		keys.append((None, external.port.name))
	return keys


def _ad_hoc_groups(linked):
	"""The ad hoc connections grouped into nets, where connections that share a port, an
	instance's or a top port (_ad_hoc_keys), directly or through other connections, are one net.
	Each group lists connection names in design order from its first one. A tied connection is
	in no net: its ports are tied on their own (step 7c, _ties)."""
	by_port = {}
	tied = _tied_connections(linked)
	names = [name for name in _ad_hoc_names(linked) if name not in tied]
	for name in names:
		for key in _ad_hoc_keys(linked, name):
			by_port.setdefault(key, []).append(name)
	groups = []
	seen = set()
	for name in names:
		if name in seen:
			continue
		group = [name]
		seen.add(name)
		for member in group:
			for key in _ad_hoc_keys(linked, member):
				for other in by_port[key]:
					if other not in seen:
						seen.add(other)
						group.append(other)
		groups.append(group)
	return groups


def _tied_connections(linked):
	"""The names of the design's ad hoc connections that have a tiedValue (step 7c)."""
	return {
		connection.name for connection in linked.design.ad_hoc_connections
		if connection.tied_value is not None
	}


def _check_tied_ports(linked):
	"""Refuse a port that a tied ad hoc connection ties and that another ad hoc connection also
	reaches, tied or not (step 7c decision 6): a port takes one expression, and the standard does
	not say which would win. A tied port on a bus net is refused in _bus_nets."""
	tied = _tied_connections(linked)
	owners = {}
	for name in _ad_hoc_names(linked):
		if name in tied:
			for key in _ad_hoc_keys(linked, name):
				owners.setdefault(key, name)
	for name in _ad_hoc_names(linked):
		for key in _ad_hoc_keys(linked, name):
			owner = owners.get(key)
			if owner is not None and owner != name:
				instance, port = key
				if instance is None:
					where = f"top port '{port}'"
				else:
					where = f"port '{port}' of instance '{instance}'"
				raise ValueError(
					f"{where} is tied by ad hoc connection '{owner}' and is also in ad hoc "
					f"connection '{name}': a tied port can't be in another connection"
				)


def _ad_hoc_nets(linked):
	"""The ad hoc nets (steps 4 and 5): the (net name, width) of each net to declare as a wire,
	in design order, and instance name -> {port name -> net name}. Connections that share a
	port are one net (_ad_hoc_groups); a port listed twice is written once. A net that reaches
	a top port is that port: it takes the port's name and is not declared, as the module header
	declares it. A net that reaches two top ports is refused. Any other net is named after its
	first connection in design order. The instance ports on a net must have the same width and
	bit order. Any mix of directions is accepted (the nets are wires). A tied connection makes
	no net (_ties), and a port it ties may be in no other connection (_check_tied_ports). What
	rtlgen can't write yet is refused in _check_reference and _check_external."""
	nets = []
	ports = {}
	sources = {}
	for ad_hoc in linked.design.ad_hoc_connections:
		if ad_hoc.name in sources:
			raise ValueError(
				f"design {linked.vlnv} has two ad hoc connections named '{ad_hoc.name}': "
				"names must be unique"
			)
		sources[ad_hoc.name] = ad_hoc
	_check_tied_ports(linked)
	model = linked.component.model or ipxact.Model()
	top_resolve = xactflow.parameter_resolver(linked.component.parameters)
	top_names = {
		port.name for port in model.ports
		if port.wire is None or port.wire.direction is not ipxact.Direction.PHANTOM
	}
	reached = set()
	for group in _ad_hoc_groups(linked):
		top_ports = []
		for member in group:
			for external in linked.ad_hoc_external_ports.get(member, []):
				if external.port.name not in top_ports:
					top_ports.append(external.port.name)
		reached.update(top_ports)
		if len(top_ports) > 1:
			raise ValueError(
				"the net of ad hoc connection(s) " + ", ".join(f"'{m}'" for m in group)
				+ " joins top ports " + ", ".join(f"'{p}'" for p in top_ports)
				+ ": a net between top ports is not supported yet"
			)
		if top_ports:
			name = top_ports[0]
		else:
			name = group[0]
			_check_name(name, f"ad hoc connection name '{name}' in design {linked.vlnv}")
			if name in top_names:
				raise ValueError(
					f"ad hoc connection '{name}' has the same name as a top port: "
					"its net and the port would clash in the module"
				)
			if name in linked.instances:
				raise ValueError(
					f"ad hoc connection '{name}' has the same name as an instance: its net and the "
					"instance would clash in the module"
				)
		references = []
		for member in group:
			for reference in _ad_hoc_references(linked, member):
				_check_reference(member, reference)
			for external in linked.ad_hoc_external_ports.get(member, []):
				_check_external(member, external)
			references.extend(_ad_hoc_references(linked, member))
		shapes = []
		for reference in references:
			bounds = _port_range(
				reference.port,
				_resolver(reference.instance),
				f"instance '{reference.instance.instance_name}'",
			)
			if bounds is None:
				width = 1
			else:
				left, right = bounds
				width = abs(left - right) + 1
			shapes.append((f"{reference.instance.instance_name}.{reference.port.name}", bounds, width))
		if top_ports:
			top_port = next(
				external.port
				for member in group
				for external in linked.ad_hoc_external_ports.get(member, [])
			)
			bounds = _port_range(top_port, top_resolve, f"component {linked.component.vlnv}")
			if bounds is None:
				width = 1
			else:
				left, right = bounds
				width = abs(left - right) + 1
			shapes.append((f"top port {top_port.name}", bounds, width))
		if len(group) == 1:
			label = f"ad hoc connection '{group[0]}'"
		else:
			label = (
				"ad hoc connections " + ", ".join(f"'{m}'" for m in group)
				+ " (one net: they share a port)"
			)
		listed = ", ".join(
			f"{where} " + (f"[{bounds[0]}:{bounds[1]}]" if bounds else "1 bit")
			for where, bounds, width in shapes
		)
		if len({width for where, bounds, width in shapes}) > 1:
			raise ValueError(
				f"{label} joins ports of different widths ({listed}): "
				"part selects are not supported yet"
			)
		if len({bounds[0] > bounds[1] for where, bounds, width in shapes if width > 1}) > 1:
			raise ValueError(
				f"{label} joins ports with opposite bit orders ({listed}): "
				"not supported yet"
			)
		if top_ports:
			# Decision 8: a top input is driven from outside, so no instance output may drive
			# it; a top output needs an instance output or inout to drive it. A top inout
			# takes any mix.
			drivers = [
				f"{reference.instance.instance_name}.{reference.port.name}"
				for reference in references
				if reference.port.wire.direction is ipxact.Direction.OUT
			]
			inouts = [
				reference for reference in references
				if reference.port.wire.direction is ipxact.Direction.INOUT
			]
			if top_port.wire.direction is ipxact.Direction.IN and drivers:
				raise ValueError(
					f"{label} drives top input '{top_port.name}' from instance output(s) "
					f"{', '.join(drivers)}: the input is driven from outside the module"
				)
			if top_port.wire.direction is ipxact.Direction.OUT and not (drivers or inouts):
				raise ValueError(
					f"{label} reaches top output '{top_port.name}', but no output or inout "
					"drives it: drive it, or tie it with a tiedValue in a connection of its own"
				)
		if not top_ports:
			nets.append((name, width))
		for reference in references:
			ports.setdefault(reference.instance.instance_name, {})[reference.port.name] = name
	for member in _tied_connections(linked):  # tied to a value, or left open on purpose (step 7c)
		for external in linked.ad_hoc_external_ports.get(member, []):
			reached.add(external.port.name)
	for port in model.ports:
		if port.wire and port.wire.direction is ipxact.Direction.OUT and port.name not in reached:
			raise ValueError(
				f"top output '{port.name}' of component {linked.component.vlnv} is not reached "
				"by any connection, so nothing drives it: connect it, or tie it with an ad hoc "
				"connection's tiedValue (a value or 'open')"
			)
	return nets, ports


def _ties(linked):
	"""The ports that the tied ad hoc connections tie (step 7c), in design order: instance name
	-> {port name -> what it is connected to}, and top output -> constant for each assign to
	write. A value or 'default' ties an instance input to a sized constant (_tie_constant), or
	drives a top output through an assign; a value on any other port is refused, as something
	else drives that port (decision 3). 'open' leaves any port open on purpose: an instance port
	is written as '.<port>()' and a top port is left unconnected (decision 4). A tied port is in
	no other connection (_check_tied_ports, _bus_nets)."""
	ports = {}
	assigns = {}
	top_resolve = xactflow.parameter_resolver(linked.component.parameters)
	for connection in linked.design.ad_hoc_connections:
		if connection.tied_value is None:
			continue
		name = connection.name
		is_open = connection.tied_value.value.strip() == "open"
		for reference in _ad_hoc_references(linked, name):
			_check_reference(name, reference)
			instance = reference.instance.instance_name
			where = f"port '{reference.port.name}' of instance '{instance}'"
			direction = reference.port.wire.direction
			if is_open:
				constant = ""
			elif direction is not ipxact.Direction.IN:
				kind = "an output" if direction is ipxact.Direction.OUT else "an inout"
				raise ValueError(
					f"ad hoc connection '{name}' ties {where}, {kind}, to a value: only an input "
					"can be tied to one, as an output or inout drives its port itself"
				)
			else:
				constant = _tie_constant(
					linked, connection, reference.port, _resolver(reference.instance),
					f"instance '{instance}'", where,
				)
			ports.setdefault(instance, {})[reference.port.name] = constant
		for external in linked.ad_hoc_external_ports.get(name, []):
			_check_external(name, external)
			if is_open:
				continue
			where = f"top port '{external.port.name}'"
			direction = external.port.wire.direction
			if direction is not ipxact.Direction.OUT:
				kind = "an input" if direction is ipxact.Direction.IN else "an inout"
				raise ValueError(
					f"ad hoc connection '{name}' ties {where}, {kind}, to a value: only a top "
					"output can be tied to one, as a top input or inout is driven from outside "
					"the module"
				)
			assigns[external.port.name] = _tie_constant(
				linked, connection, external.port, top_resolve,
				f"component {linked.component.vlnv}", where,
			)
	return ports, assigns


def _tie_constant(linked, connection, port, resolve, owner, where):
	"""The sized constant a tied connection ties a port to (step 7c decisions 2, 5 and 7): its
	tiedValue, or for 'default' the port's own default value, worked out with resolve, the
	owner's parameters. The value must work out to a whole number from 0 to 2^W - 1 for a port
	of W bits, and is written in hex ('16'hff'), or in binary for one bit ('1'b0'). A fill
	literal ('0, '1, 'x, 'z), a real or negative number, a value too big for the port, and one
	that can't be worked out are refused: SCR 14.1 makes a tie value an unsigned bit vector."""
	bounds = _port_range(port, resolve, owner)
	width = 1 if bounds is None else abs(bounds[0] - bounds[1]) + 1
	ties = f"ad hoc connection '{connection.name}' ties {where} ({width} bit{'s' * (width > 1)})"
	text = connection.tied_value.value.strip()
	if text == "default":
		text = _default_value(port, ties)
		ties += f" to its default value {text}"
	else:
		ties += f" to {text}"
		resolve = xactflow.parameter_resolver(linked.design.parameters)
	if _FILL.search(text):
		raise ValueError(
			f"{ties}: fill literals ('0, '1, 'x, 'z) are not supported, write the bits as a sized "
			"literal, such as 8'hff"
		)
	try:
		value = xactflow.evaluate(text, resolve)
	except xactflow.ExpressionError as error:
		raise ValueError(f"{ties}, which cannot be worked out: {error}") from error
	if not isinstance(value, int):
		raise ValueError(f"{ties}, which works out to {value!r}: a tie value is a whole number")
	if value < 0:
		raise ValueError(f"{ties}, which works out to {value}: a tie value can't be negative")
	if value >= 1 << width:
		raise ValueError(f"{ties}, which works out to {value}: too big for the port")
	return f"1'b{value}" if width == 1 else f"{width}'h{value:x}"


def _default_value(port, ties):
	"""The default value of a port tied with tiedValue 'default' (step 7c decision 5): the
	defaultValue of its one driver. A port with none is refused (SCR 6.25, and SCR 6.23 for an
	output), and so is a driver rtlgen can't write."""
	ties += " to its default value ('default')"
	if port.wire.direction is ipxact.Direction.OUT:
		raise ValueError(f"{ties}, but an output has no default value (SCR 6.23)")
	drivers = port.wire.drivers
	if not drivers:
		raise ValueError(f"{ties}, but the port has none (SCR 6.25)")
	if len(drivers) > 1:
		raise ValueError(
			f"{ties}, but the port has {len(drivers)} drivers: several are not supported yet"
		)
	driver = drivers[0]
	if driver.default_value is None:
		raise ValueError(
			f"{ties}, but its driver is a clockDriver or singleShotDriver, not a default value"
		)
	if driver.range is not None or driver.view_refs:
		raise ValueError(
			f"{ties}, but its driver is only for part of the port (range) or for some views "
			"(viewRef): not supported yet"
		)
	return driver.default_value.value.strip()


def _assign_lines(linked):
	"""'  assign <top output> = <constant>;' for each top output tied to a value, in design order,
	then a blank line; nothing when there is none (step 7c decision 3)."""
	_, assigns = _ties(linked)
	lines = "".join(f"  assign {port} = {constant};\n" for port, constant in assigns.items())
	return lines + "\n" if lines else ""


def _bus_nets(linked):
	"""The bus nets (step 6): for each interconnection in design order, (its name, [(net name,
	width), ...]), and instance name -> {port name -> net name}. Each logical port that both
	ends map is one net, named <interconnection>_<logical port>, in the first end's port-map
	order (D18). The checks are D19's; what rtlgen can't wire yet is refused here and in
	_check_interconnection and _check_port_maps (D20)."""
	groups = []
	ports = {}
	ad_hoc, _ = _ad_hoc_nets(linked)
	model = linked.component.model or ipxact.Model()
	taken = {
		port.name: f"top port '{port.name}'" for port in model.ports
		if port.wire is None or port.wire.direction is not ipxact.Direction.PHANTOM
	}
	taken.update({name: f"instance '{name}'" for name in linked.instances})
	taken.update({name: f"ad hoc net '{name}'" for name, width in ad_hoc})
	ad_hoc_ports = {}
	for connection in _ad_hoc_names(linked):
		for key in _ad_hoc_keys(linked, connection):
			ad_hoc_ports.setdefault(key, connection)
	tied = _tied_connections(linked)
	for monitor in linked.monitor_interconnections:
		raise ValueError(
			f"monitor interconnection '{monitor.name}' in design {linked.vlnv}: "
			"monitor interconnections are not supported yet"
		)
	names = set()
	for interconnection in linked.interconnections:
		if interconnection.name in names:
			raise ValueError(
				f"design {linked.vlnv} has two interconnections named '{interconnection.name}': "
				"names must be unique"
			)
		names.add(interconnection.name)
		_check_interconnection(interconnection)
		first, second = interconnection.endpoints
		first_maps = {port_map.logical_port: port_map.physical_port
			for port_map in first.bus_interface.abstraction_types[0].port_maps}
		second_maps = {port_map.logical_port: port_map.physical_port
			for port_map in second.bus_interface.abstraction_types[0].port_maps}
		ends = ((second, second_maps, first_maps), (first, first_maps, second_maps))
		for end, maps, other in ends:
			missing = [logical for logical in other if logical not in maps]
			if missing:
				raise ValueError(
					f"interconnection '{interconnection.name}': bus interface "
					f"'{end.bus_interface.name}' of instance '{end.instance.instance_name}' "
					f"does not map logical port(s) {', '.join(missing)}, which the other end "
					"maps: unconnected bus ports are not supported yet"
				)
		nets = []
		for logical, physical in first_maps.items():
			net = f"{interconnection.name}_{logical}"
			what = f"bus net '{net}' of interconnection '{interconnection.name}'"
			_check_name(net, what)
			if net in taken:
				raise ValueError(
					f"{what} has the same name as {taken[net]}: they would clash in the module"
				)
			taken[net] = what
			sides = [(first, physical), (second, second_maps[logical])]
			width = _bus_net_width(net, sides)
			_check_bus_directions(net, sides)
			nets.append((net, width))
			for end, name in sides:
				instance = end.instance.instance_name
				if ad_hoc_ports.get((instance, name)) in tied:  # step 7c decision 6
					raise ValueError(
						f"port '{name}' of instance '{instance}' is on {what} and is tied by "
						f"ad hoc connection '{ad_hoc_ports[(instance, name)]}': a tied port "
						"can't be in another connection"
					)
				if (instance, name) in ad_hoc_ports:
					raise ValueError(
						f"port '{name}' of instance '{instance}' is on {what} and in ad hoc "
						f"connection '{ad_hoc_ports[(instance, name)]}': a port on both is not "
						"supported yet"
					)
				ports.setdefault(instance, {})[name] = net
		groups.append((interconnection.name, nets))
	return groups, ports


def _bus_net_width(net, sides):
	"""The width of a bus net, from its two sides as (end, port name): both ports need the same
	width and bit order (D12, D19 item 2)."""
	shapes = []
	for end, name in sides:
		instance = end.instance.instance_name
		port = next(p for p in end.instance.component.model.ports if p.name == name)
		bounds = _port_range(port, _resolver(end.instance), f"instance '{instance}'")
		width = 1 if bounds is None else abs(bounds[0] - bounds[1]) + 1
		shapes.append((f"{instance}.{name}", bounds, width))
	listed = ", ".join(
		f"{where} " + (f"[{bounds[0]}:{bounds[1]}]" if bounds else "1 bit")
		for where, bounds, width in shapes
	)
	if len({width for where, bounds, width in shapes}) > 1:
		raise ValueError(
			f"bus net '{net}' joins ports of different widths ({listed}): "
			"part selects are not supported yet"
		)
	if len({bounds[0] > bounds[1] for where, bounds, width in shapes if width > 1}) > 1:
		raise ValueError(
			f"bus net '{net}' joins ports with opposite bit orders ({listed}): not supported yet"
		)
	return shapes[0][2]


def _check_bus_directions(net, sides):
	"""Refuse a bus net that nothing drives or that two outputs drive (D19 item 3). An inout on
	either side is accepted."""
	directions = []
	for end, name in sides:
		port = next(p for p in end.instance.component.model.ports if p.name == name)
		directions.append((f"{end.instance.instance_name}.{name}", port.wire.direction))
	listed = ", ".join(f"{where} ({direction.value})" for where, direction in directions)
	kinds = {direction for where, direction in directions}
	if kinds == {ipxact.Direction.IN}:
		raise ValueError(f"bus net '{net}' joins two inputs ({listed}): nothing drives it")
	if kinds == {ipxact.Direction.OUT}:
		raise ValueError(f"bus net '{net}' joins two outputs ({listed}): both drive it")


def _check_interconnection(interconnection):
	"""Refuse an interconnection that rtlgen can't wire yet (D20 items 2 and 3)."""
	name = interconnection.name
	if interconnection.hier_interfaces:
		raise ValueError(
			f"interconnection '{name}' reaches bus interface "
			f"'{interconnection.hier_interfaces[0].source.bus_ref}' of the top (a hierInterface): "
			"top-level bus interfaces are not supported yet"
		)
	if len(interconnection.endpoints) != 2:
		raise ValueError(
			f"interconnection '{name}' has {len(interconnection.endpoints)} "
			"active interfaces: only two are supported (no broadcast)"
		)
	modes = {end.bus_interface.mode for end in interconnection.endpoints}
	if modes != {ipxact.InterfaceMode.INITIATOR, ipxact.InterfaceMode.TARGET}:
		listed = " and ".join(
			f"{end.instance.instance_name}.{end.bus_interface.name} "
			f"({end.bus_interface.mode.value})"
			for end in interconnection.endpoints
		)
		raise ValueError(
			f"interconnection '{name}' joins {listed}: only an initiator with a target is "
			"supported yet"
		)
	for end in interconnection.endpoints:
		where = (
			f"bus interface '{end.bus_interface.name}' of instance "
			f"'{end.instance.instance_name}' in interconnection '{name}'"
		)
		count = len(end.bus_interface.abstraction_types)
		if count != 1:
			raise ValueError(
				f"{where} has {count} abstractionTypes: only one is supported yet"
			)
		if end.source.exclude_ports:
			excluded = ", ".join(port.value for port in end.source.exclude_ports)
			raise ValueError(
				f"{where} excludes logical ports {excluded}: excludePorts is not supported yet"
			)
		_check_port_maps(where, end)


def _check_port_maps(where, end):
	"""Refuse a port map of an interconnection's end that rtlgen can't wire yet (D20 item 4)."""
	ports = {port.name: port for port in end.instance.component.model.ports}
	logicals = set()
	physicals = {}
	for port_map in end.bus_interface.abstraction_types[0].port_maps:
		logical = port_map.logical_port
		physical = port_map.physical_port
		maps = f"{where} maps logical port '{logical}'"
		if logical in logicals:
			raise ValueError(f"{maps} twice: not supported yet")
		logicals.add(logical)
		if port_map.is_informative:
			raise ValueError(f"{maps} for information only (isInformative): not supported yet")
		if port_map.logical_tie_off is not None:
			raise ValueError(
				f"{maps} to a constant (logicalTieOff): tie-offs are not supported yet"
			)
		if port_map.invert:
			raise ValueError(f"{maps} inverted (invert): not supported yet")
		if port_map.logical_range is not None:
			raise ValueError(
				f"{maps} in part (logicalRange): part selects are not supported yet"
			)
		if port_map.part_select is not None:
			raise ValueError(
				f"{maps} to part of port '{physical}' (partSelect): "
				"part selects are not supported yet"
			)
		if port_map.sub_port_refs:
			raise ValueError(
				f"{maps} to a sub-port of port '{physical}' (subPortReference): "
				"sub-ports of structured ports are not supported yet"
			)
		if physical in physicals:
			raise ValueError(
				f"{where} maps port '{physical}' twice (logical ports "
				f"'{physicals[physical]}' and '{logical}'): not supported yet"
			)
		physicals[physical] = logical
		port = ports.get(physical)
		if port is None:
			raise ValueError(f"{maps} to port '{physical}', which the component does not have")
		_check_name(
			physical, f"port name '{physical}' of instance '{end.instance.instance_name}'"
		)
		if port.wire is None:
			raise ValueError(
				f"{maps} to port '{physical}', which is not a wire port: "
				"transactional and structured ports are not supported yet"
			)
		if port.wire.direction is ipxact.Direction.PHANTOM:
			raise ValueError(
				f"{maps} to port '{physical}', which is phantom: it is not in the module"
			)
		if port.arrays:
			raise ValueError(
				f"{maps} to port '{physical}', which is an array: port arrays are not supported yet"
			)


def _check_reference(connection, reference):
	"""Refuse a port reference that rtlgen can't write yet."""
	_check_name(
		reference.port.name,
		f"port name '{reference.port.name}' of instance '{reference.instance.instance_name}'"
	)
	if reference.port.wire is None:
		raise ValueError(
			f"ad hoc connection '{connection}' connects port '{reference.port.name}' "
			f"of instance '{reference.instance.instance_name}', which is "
			"not a wire port: transactional and structured ports are not supported yet"
		)
	if reference.port.wire.direction is ipxact.Direction.PHANTOM:
		raise ValueError(
			f"ad hoc connection '{connection}' connects port '{reference.port.name}' "
			f"of instance '{reference.instance.instance_name}', which is "
			"phantom: it is not in the module"
		)
	if reference.port.arrays:
		raise ValueError(
			f"ad hoc connection '{connection}' connects port '{reference.port.name}' "
			f"of instance '{reference.instance.instance_name}', which is "
			"an array: port arrays are not supported yet"
		)
	if reference.source.part_select is not None:
		raise ValueError(
			f"ad hoc connection '{connection}' takes a part of port '{reference.port.name}' "
			f"of instance '{reference.instance.instance_name}' (partSelect): "
			"part selects are not supported yet"
		)
	if reference.source.sub_port_refs:
		raise ValueError(
			f"ad hoc connection '{connection}' connects a sub-port of port '{reference.port.name}' "
			f"of instance '{reference.instance.instance_name}' (subPortReference): "
			"sub-ports of structured ports are not supported yet"
		)


def _check_external(connection, external):
	"""Refuse a top-port reference that rtlgen can't write yet (decisions 10 and 11)."""
	where = f"ad hoc connection '{connection}' connects top port '{external.port.name}'"
	if external.port.wire is None:
		raise ValueError(
			f"{where}, which is not a wire port: transactional and structured ports are "
			"not supported yet"
		)
	if external.port.wire.direction is ipxact.Direction.PHANTOM:
		raise ValueError(f"{where}, which is phantom: it is not in the module")
	if external.source.part_select is not None:
		raise ValueError(
			f"{where} through a partSelect: part selects are not supported yet"
		)
	if external.source.sub_port_refs:
		raise ValueError(
			f"{where} through a subPortReference: sub-ports of structured ports are not "
			"supported yet"
		)


def _port_range(port, resolve, owner):
	"""A port's (left, right) bounds, worked out with resolve, or None for a port with no
	vector (one bit). A port with several vectors is refused for now, naming the port and
	its owner (an instance, or the containing component for a top port)."""
	vectors = port.wire.vectors
	if not vectors:
		return None
	if len(vectors) > 1:
		raise ValueError(
			f"port '{port.name}' of {owner} has {len(vectors)} "
			"vectors: multi-dimensional ports are not supported yet"
		)
	try:
		left = xactflow.evaluate(vectors[0].left, resolve)
		right = xactflow.evaluate(vectors[0].right, resolve)
	except xactflow.ExpressionError as error:
		raise ValueError(
			f"{owner}: the range of port '{port.name}' cannot be "
			f"worked out: {error}"
		) from error
	return (left, right)


def _resolver(instance):
	"""The resolver for an instance's values: its component's parameters, with the design's
	overrides in place (D6 item 2)."""
	overrides = instance.source.component_ref.config_element_values
	parameter_ids = {p.parameter_id for p in instance.component.parameters}
	for reference_id in overrides:
		if reference_id not in parameter_ids:
			raise ValueError(
				f"instance '{instance.instance_name}' overrides '{reference_id}', which is not "
				f"a parameter of component {instance.component.vlnv}"
			)
	# The component's parameters, each with the design's override for this instance in place
	# of its value. The override replaces only the text: the limits stay the parameter's.
	parameters = [
		dataclasses.replace(
			parameter,
			value=dataclasses.replace(parameter.value, value=overrides[parameter.parameter_id].value),
		)
		if parameter.parameter_id in overrides
		else parameter
		for parameter in instance.component.parameters
	]
	return xactflow.parameter_resolver(parameters)


def _module_parameter_lines(instance, instantiation):
	"""'    .<name>(<value>)' for every module parameter of the instantiation, in its order, with
	its value in this design (D6, D7)."""
	names = set()
	resolve = _resolver(instance)
	for parameter in instantiation.module_parameters:
		_check_name(
			parameter.name,
			f"module parameter name '{parameter.name}' of instance '{instance.instance_name}'"
		)
		if parameter.name in names:
			raise ValueError(
				f"instance '{instance.instance_name}' gives module parameter '{parameter.name}' twice"
			)
		names.add(parameter.name)
	return [
		f"    .{parameter.name}({_module_parameter_value(parameter, resolve, instance)})"
		for parameter in instantiation.module_parameters
	]


def _module_parameter_value(parameter, resolve, instance):
	"""A module parameter's value as written: as it stands when it refers to no parameter,
	else worked out by XactFlow's evaluator and written as plain decimal (D7)."""
	if parameter.usage_type not in ("typed", None):
		raise ValueError(
			f"instance '{instance.instance_name}': module parameter '{parameter.name}' has "
			f"usageType '{parameter.usage_type}': only typed module parameters are supported"
		)
	text = parameter.value.value.strip()
	if not _IDENTIFIER.search(_NOT_A_PARAMETER.sub(" ", text)):
		return text
	try:
		return str(xactflow.evaluate(parameter, resolve))
	except xactflow.ExpressionError as error:
		raise ValueError(
			f"instance '{instance.instance_name}': module parameter '{parameter.name}' "
			f"('{text}') cannot be worked out: {error}"
		) from error


def _module_name(linked):
	"""The name of the module generated for a linked design, as D1 decides it. Refuses the
	top's own parameters (D8)."""
	if linked.design.parameters:
		raise ValueError(
			f"design {linked.vlnv} has parameters of its own: the top's parameters are not "
			"supported yet"
		)
	component = linked.component
	if component is None:  # D1 item 2
		raise ValueError(
			f"no component in the library holds design {linked.vlnv}: add the component that "
			"holds it (with archidesc, the --then component output)"
		)
	model = component.model or ipxact.Model()
	design_instantiations = {i.name: i for i in model.design_instantiations}
	component_instantiations = {i.name: i for i in model.component_instantiations}

	# View name -> module name, for each view whose designInstantiationRef leads to the
	# design (D1 item 1), each of which must give a name (D1 item 3).
	names = {}
	for view in model.views:
		design_instantiation = design_instantiations.get(view.design_instantiation_ref)
		if design_instantiation is None or design_instantiation.design_ref.vlnv != linked.vlnv:
			continue
		where = f"view '{view.name}' of component {component.vlnv}"
		if view.component_instantiation_ref is None:
			raise ValueError(f"{where} has no componentInstantiationRef, so it names no module")
		instantiation = _component_instantiation(view, component_instantiations, where)
		if instantiation.module_parameters:
			raise ValueError(
				f"{where} gives the top module parameters: the top's parameters are not "
				"supported yet"
			)
		names[view.name] = instantiation.module_name

	if not names:  # D1 item 6
		raise ValueError(
			f"no view of component {component.vlnv} instantiates design {linked.vlnv} through a "
			"designInstantiationRef (a view through a design configuration is not supported yet)"
		)
	if len(set(names.values())) > 1:  # D1 item 4
		listed = ", ".join(f"view '{view}' gives '{name}'" for view, name in names.items())
		raise ValueError(
			f"the views of component {component.vlnv} instantiating design {linked.vlnv} give "
			f"different module names: {listed}"
		)
	module_name = next(iter(names.values()))
	_check_name(module_name, f"module name '{module_name}' from component {component.vlnv}")
	return module_name


def _top_port_lines(linked):
	"""The module header's port lines, '  <direction> wire [<left>:<right>] <name>' (no range for
	one bit): one for each port of the containing component, connected or not, in its order,
	with its bounds worked out with the component's parameters and kept as they are (D14). A
	phantom port is not in the module, so it is left out. A port rtlgen can't declare yet is
	refused: one that is not a wire port, an array, one with several vectors (in _port_range),
	or one whose name is not a legal identifier or is an instance's (D16, D17)."""
	component = linked.component
	model = component.model or ipxact.Model()
	resolve = xactflow.parameter_resolver(component.parameters)
	lines = []
	dir_kws = {
		ipxact.Direction.IN: "input",
		ipxact.Direction.OUT: "output",
		ipxact.Direction.INOUT: "inout",
	}
	for port in model.ports:
		if port.wire is None:
			raise ValueError(
				f"top port '{port.name}' of component {component.vlnv} is not a wire port: "
				"transactional and structured ports are not supported yet"
			)
		if port.wire.direction is ipxact.Direction.PHANTOM:
			continue
		_check_name(port.name, f"top port name '{port.name}' of component {component.vlnv}")
		if port.name in linked.instances:
			raise ValueError(
				f"top port '{port.name}' of component {component.vlnv} has the same name as "
				"an instance: the port and the instance would clash in the module"
			)
		if port.arrays:
			raise ValueError(
				f"top port '{port.name}' of component {component.vlnv} is an array: "
				"port arrays are not supported yet"
			)
		bounds = _port_range(port, resolve, f"component {component.vlnv}")
		if bounds is None:
			range_text = ""
		else:
			left, right = bounds
			range_text = f" [{left}:{right}]"
		lines.append(f"  {dir_kws[port.wire.direction]} wire{range_text} {port.name}")
	return lines


def _instance_instantiation(instance):
	"""The component instantiation an instance instantiates: the one its component's views
	with a componentInstantiationRef lead to, whose moduleName names the module (D4)."""
	component = instance.component
	model = component.model or ipxact.Model()
	component_instantiations = {i.name: i for i in model.component_instantiations}
	who = f"component {component.vlnv} (instance '{instance.instance_name}')"

	# A view that instantiates a design makes the component hierarchical, which waits for
	# step 8, whichever view would give the module name.
	for view in model.views:
		if view.design_instantiation_ref or view.design_configuration_instantiation_ref:
			raise ValueError(
				f"view '{view.name}' of {who} instantiates a design, so the component is "
				"hierarchical: hierarchical components are not supported yet"
			)

	# View name -> component instantiation, for each view with a componentInstantiationRef. A
	# view with none (documentation, say) is skipped.
	chosen = {}
	for view in model.views:
		if view.component_instantiation_ref is None:
			continue
		where = f"view '{view.name}' of {who}"
		component_instantiation = _component_instantiation(view, component_instantiations, where)
		# Only SystemVerilog, compared ignoring case. A missing language is accepted.
		language = (component_instantiation.language or "").strip()
		if language and language.lower() != "systemverilog":
			raise ValueError(
				f"component instantiation '{component_instantiation.name}' of {where} is in "
				f"language '{language}': only SystemVerilog is supported"
			)
		# IEEE 1685-2022: a virtual component "shall not be netlisted". Refused for now.
		if component_instantiation.is_virtual:
			raise ValueError(
				f"component instantiation '{component_instantiation.name}' of {where} is virtual "
				"(isVirtual): virtual components are not supported yet"
			)
		chosen[view.name] = component_instantiation

	if not chosen:
		raise ValueError(
			f"no view of {who} has a componentInstantiationRef, so nothing names its module"
		)
	if len({i.module_name for i in chosen.values()}) > 1:
		listed = ", ".join(f"view '{view}' gives '{i.module_name}'" for view, i in chosen.items())
		raise ValueError(f"the views of {who} give different module names: {listed}")
	parameter_lines = {view: _module_parameter_lines(instance, i) for view, i in chosen.items()}
	if len({tuple(lines) for lines in parameter_lines.values()}) > 1:
		listed = "; ".join(
			f"view '{view}' gives {', '.join(line.strip() for line in lines) or 'none'}"
			for view, lines in parameter_lines.items()
		)
		raise ValueError(f"the views of {who} give different module parameters: {listed}")
	instantiation = next(iter(chosen.values()))
	_check_name(instantiation.module_name, f"module name '{instantiation.module_name}' of {who}")
	return instantiation


def _component_instantiation(view, component_instantiations, where):
	"""The component instantiation a view's componentInstantiationRef names, refusing one that
	does not exist or gives no moduleName (D1 item 3, and D4 for instances)."""
	component_instantiation = component_instantiations.get(view.component_instantiation_ref)
	if component_instantiation is None:
		raise ValueError(
			f"{where} refers to component instantiation "
			f"'{view.component_instantiation_ref}', which the component does not have"
		)
	if not component_instantiation.module_name:
		raise ValueError(
			f"component instantiation '{component_instantiation.name}' of {where} "
			"has no moduleName"
		)
	return component_instantiation
