"""D2: only files rtlgen wrote are overwritten."""
import pytest

from conftest import EXPECTED_SOC_A
from rtlgen import RtlExporter


def test_missing_output_folder_is_created(library, tmp_path):
	output = tmp_path / "a" / "b"
	RtlExporter().export(library, output)
	assert (output / "soc_a.sv").read_text() == EXPECTED_SOC_A


def test_own_file_is_overwritten(library, tmp_path):
	(tmp_path / "soc_a.sv").write_text("// Generated by rtlgen from an older run\nold\n")
	RtlExporter().export(library, tmp_path)
	assert (tmp_path / "soc_a.sv").read_text() == EXPECTED_SOC_A


def test_hand_written_file_is_kept(library, tmp_path):
	hand_written = "module soc_a; // mine\nendmodule\n"
	(tmp_path / "soc_a.sv").write_text(hand_written)
	with pytest.raises(ValueError, match="not written by rtlgen"):
		RtlExporter().export(library, tmp_path)
	assert (tmp_path / "soc_a.sv").read_text() == hand_written
